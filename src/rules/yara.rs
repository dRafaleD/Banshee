//! Conversion between Banshee TOML rules and a documented subset of YARA.
//!
//! Export never widens or narrows a rule silently: anything YARA cannot
//! express is either written as an explicit warning comment (when the YARA
//! rule would only match more broadly) or the rule is skipped with a reason.
//! Import accepts only constructs with an exact Banshee equivalent and checks
//! the generated TOML with the regular rule compiler before returning it.

use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, Result, bail};
use serde::Serialize;

use super::{
    RuleCondition, RuleDefinition, RuleFileType, RuleKind, TextEncoding, compile_source,
    literal_pattern, load_and_compile, parse_hex_pattern, regex_pattern,
};

/// Compiles a regular expression once and reuses it for every rule.
macro_rules! regex {
    ($pattern:expr) => {{
        static CELL: std::sync::OnceLock<regex::Regex> = std::sync::OnceLock::new();
        CELL.get_or_init(|| regex::Regex::new($pattern).expect("valid built-in regex"))
    }};
}

const MAX_YARA_FILE_BYTES: u64 = 1024 * 1024;

#[derive(Debug, Clone, Serialize)]
pub struct Conversion {
    pub output: String,
    pub converted: usize,
    pub skipped: Vec<SkippedRule>,
    pub warnings: Vec<String>,
}

#[derive(Debug, Clone, Serialize)]
pub struct SkippedRule {
    pub rule: String,
    pub reason: String,
}

// ---------------------------------------------------------------------------
// Banshee -> YARA

pub fn export_file(path: &Path) -> Result<Conversion> {
    let rules = load_and_compile(path)?;
    let definitions = rules
        .rules
        .into_iter()
        .map(|rule| rule.definition)
        .collect::<Vec<_>>();
    Ok(export_definitions(&definitions))
}

fn export_definitions(definitions: &[RuleDefinition]) -> Conversion {
    let mut bodies = Vec::new();
    let mut skipped = Vec::new();
    let mut warnings = Vec::new();
    let mut names = HashSet::new();
    let mut needs_math = false;
    for definition in definitions {
        match export_rule(definition, &mut names) {
            Ok(exported) => {
                needs_math |= exported.uses_math;
                for warning in &exported.warnings {
                    warnings.push(format!("{}: {warning}", definition.id));
                }
                bodies.push(exported.text);
            }
            Err(reason) => skipped.push(SkippedRule {
                rule: definition.id.clone(),
                reason: format!("{reason:#}"),
            }),
        }
    }
    let mut output = String::from(
        "// Generated by Banshee from local TOML rules. Matches are triage signals,\n\
         // not verdicts; review warning comments before deploying these rules.\n",
    );
    if needs_math {
        output.push_str("import \"math\"\n");
    }
    for rule in &skipped {
        writeln!(output, "// skipped {}: {}", rule.rule, rule.reason).expect("string write");
    }
    for body in &bodies {
        output.push('\n');
        output.push_str(body);
    }
    Conversion {
        output,
        converted: bodies.len(),
        skipped,
        warnings,
    }
}

struct ExportedRule {
    text: String,
    warnings: Vec<String>,
    uses_math: bool,
}

fn export_rule(rule: &RuleDefinition, names: &mut HashSet<String>) -> Result<ExportedRule> {
    let mut warnings = Vec::new();
    let mut strings = vec![(
        "$p".to_owned(),
        yara_string(
            rule.kind,
            &rule.pattern,
            rule.case_insensitive,
            rule.encoding,
        )?,
    )];
    for (index, condition) in rule.all.iter().enumerate() {
        strings.push((format!("$all{index}"), condition_string(condition)?));
    }
    for (index, condition) in rule.any.iter().enumerate() {
        strings.push((format!("$any{index}"), condition_string(condition)?));
    }

    let mut terms = vec![if rule.min_matches > 1 {
        format!("#p >= {}", rule.min_matches)
    } else {
        "$p".to_owned()
    }];
    terms.extend(
        rule.all
            .iter()
            .enumerate()
            .filter(|(_, condition)| condition.within.is_none())
            .map(|(index, _)| format!("$all{index}")),
    );
    let near: Vec<String> = rule
        .all
        .iter()
        .enumerate()
        .filter_map(|(index, condition)| {
            condition
                .within
                .map(|bytes| format!("$all{index} in (@p[i] .. @p[i] + {bytes})"))
        })
        .collect();
    if !near.is_empty() {
        terms.push(format!(
            "for any i in (1 .. #p) : ( {} )",
            near.join(" and ")
        ));
    }
    if !rule.any.is_empty() {
        terms.push("any of ($any*)".to_owned());
    }
    let magic = rule
        .file_types
        .iter()
        .filter_map(|file_type| {
            let expression = file_type_condition(*file_type);
            if expression.is_none() {
                warnings.push(format!(
                    "file type '{file_type}' has no YARA magic check; the YARA rule matches more broadly"
                ));
            }
            expression
        })
        .collect::<Vec<_>>();
    if !magic.is_empty() && magic.len() == rule.file_types.len() {
        terms.push(format!("({})", magic.join(" or ")));
    } else if !magic.is_empty() {
        warnings.push("only part of the file_types predicate was exported".to_owned());
    }
    let mut uses_math = false;
    if let Some(minimum) = rule.min_entropy {
        terms.push(format!("math.entropy(0, filesize) >= {minimum}"));
        uses_math = true;
    }
    if let Some(maximum) = rule.max_entropy {
        terms.push(format!("math.entropy(0, filesize) <= {maximum}"));
        uses_math = true;
    }
    if let Some(minimum) = rule.min_size {
        terms.push(format!("filesize >= {minimum}"));
    }
    if let Some(maximum) = rule.max_size {
        terms.push(format!("filesize <= {maximum}"));
    }

    let name = unique_identifier(&rule.id, names);
    let tags = rule
        .tags
        .iter()
        .map(|tag| sanitize_identifier(tag))
        .collect::<Vec<_>>();
    let mut text = String::new();
    write!(text, "rule {name}").expect("string write");
    if !tags.is_empty() {
        write!(text, " : {}", tags.join(" ")).expect("string write");
    }
    text.push_str("\n{\n    meta:\n");
    let mut meta = vec![("banshee_id", rule.id.clone())];
    if !rule.description.is_empty() {
        meta.push(("description", rule.description.clone()));
    }
    meta.push(("severity", rule.severity.to_string()));
    if let Some(category) = &rule.category {
        meta.push(("category", category.clone()));
    }
    if let Some(confidence) = rule.confidence {
        meta.push(("confidence", confidence.to_string()));
    }
    if !rule.attack.is_empty() {
        meta.push(("attack", rule.attack.join(", ")));
    }
    for reference in &rule.references {
        meta.push(("reference", reference.clone()));
    }
    for (key, value) in meta {
        writeln!(text, "        {key} = {}", quote_text(value.as_bytes())).expect("string write");
    }
    for warning in &warnings {
        writeln!(text, "        // warning: {warning}").expect("string write");
    }
    text.push_str("    strings:\n");
    for (identifier, string) in &strings {
        writeln!(text, "        {identifier} = {string}").expect("string write");
    }
    writeln!(text, "    condition:\n        {}\n}}", terms.join(" and ")).expect("string write");
    Ok(ExportedRule {
        text,
        warnings,
        uses_math,
    })
}

fn condition_string(condition: &RuleCondition) -> Result<String> {
    yara_string(
        condition.kind,
        &condition.pattern,
        condition.case_insensitive,
        condition.encoding,
    )
}

fn yara_string(
    kind: RuleKind,
    pattern: &str,
    case_insensitive: bool,
    encoding: TextEncoding,
) -> Result<String> {
    let nocase = if case_insensitive { " nocase" } else { "" };
    let width = match encoding {
        TextEncoding::Ascii => "",
        TextEncoding::Wide => " wide",
        TextEncoding::Both => " ascii wide",
    };
    match kind {
        RuleKind::Literal => Ok(format!("{}{width}{nocase}", quote_text(pattern.as_bytes()))),
        RuleKind::Hex => {
            let tokens = parse_hex_pattern(pattern)?
                .iter()
                .map(|byte| byte.map_or_else(|| "??".to_owned(), |byte| format!("{byte:02X}")))
                .collect::<Vec<_>>();
            Ok(format!("{{ {} }}", tokens.join(" ")))
        }
        RuleKind::Regex => {
            let (body, flags) = yara_regex(pattern)?;
            let nocase = if case_insensitive || flags.contains('i') {
                " nocase"
            } else {
                ""
            };
            let dotall = if flags.contains('s') { "s" } else { "" };
            Ok(format!("/{body}/{dotall}{width}{nocase}"))
        }
    }
}

/// Translates a Rust regex into YARA syntax, returning leading inline flags.
fn yara_regex(pattern: &str) -> Result<(String, String)> {
    let mut body = pattern;
    let mut flags = String::new();
    if let Some(rest) = body.strip_prefix("(?")
        && let Some(end) = rest.find(')')
        && rest[..end].chars().all(|flag| matches!(flag, 'i' | 's'))
    {
        flags = rest[..end].to_owned();
        body = &rest[end + 1..];
    }
    // YARA has no non-capturing groups; captures do not affect matching there.
    let body = body.replace("(?:", "(");
    let body = body.as_str();
    for (needle, feature) in [
        ("(?", "inline flags or non-capturing extensions"),
        ("\\p", "Unicode classes"),
        ("\\P", "Unicode classes"),
        ("\\A", "\\A anchors"),
        ("\\z", "\\z anchors"),
        ("\\x{", "\\x{...} escapes"),
        ("[[:", "POSIX classes"),
        ("\\Q", "quoted literals"),
    ] {
        if body.contains(needle) {
            bail!("regex uses {feature}, which YARA does not support");
        }
    }
    let mut escaped = String::with_capacity(body.len());
    let mut previous_backslash = false;
    for character in body.chars() {
        if character == '/' && !previous_backslash {
            escaped.push('\\');
        }
        previous_backslash = character == '\\' && !previous_backslash;
        escaped.push(character);
    }
    Ok((escaped, flags))
}

fn file_type_condition(file_type: RuleFileType) -> Option<&'static str> {
    Some(match file_type {
        RuleFileType::Pe => "uint16(0) == 0x5A4D",
        RuleFileType::Elf => "uint32(0) == 0x464C457F",
        RuleFileType::Zip => "uint32(0) == 0x04034B50",
        RuleFileType::Gzip => "uint16(0) == 0x8B1F",
        RuleFileType::Xz => "uint32(0) == 0x587A37FD",
        RuleFileType::Bzip2 => "uint16(0) == 0x5A42 and uint8(2) == 0x68",
        RuleFileType::Tar => "uint32(257) == 0x61747375",
        RuleFileType::Text | RuleFileType::Binary => return None,
    })
}

fn quote_text(bytes: &[u8]) -> String {
    let mut output = String::from("\"");
    for byte in bytes {
        match byte {
            b'"' => output.push_str("\\\""),
            b'\\' => output.push_str("\\\\"),
            b'\n' => output.push_str("\\n"),
            b'\r' => output.push_str("\\r"),
            b'\t' => output.push_str("\\t"),
            0x20..=0x7E => output.push(char::from(*byte)),
            other => write!(output, "\\x{other:02x}").expect("string write"),
        }
    }
    output.push('"');
    output
}

fn sanitize_identifier(value: &str) -> String {
    let mut identifier = value
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() || character == '_' {
                character
            } else {
                '_'
            }
        })
        .collect::<String>();
    if identifier.is_empty() || identifier.starts_with(|character: char| character.is_ascii_digit())
    {
        identifier.insert_str(0, "r_");
    }
    identifier.truncate(128);
    identifier
}

fn unique_identifier(value: &str, names: &mut HashSet<String>) -> String {
    let base = sanitize_identifier(value);
    let mut candidate = base.clone();
    let mut suffix = 2;
    while !names.insert(candidate.clone()) {
        candidate = format!("{base}_{suffix}");
        suffix += 1;
    }
    candidate
}

