// YARA -> Banshee

#[derive(Debug, Clone)]
struct YaraString {
    kind: RuleKind,
    pattern: String,
    case_insensitive: bool,
    encoding: TextEncoding,
    /// Bytes after the anchor (primary) match, for proximity conditions.
    within: Option<usize>,
}

pub fn import_file(path: &Path) -> Result<Conversion> {
    let source =
        crate::input::read_regular_text_file_limited(path, MAX_YARA_FILE_BYTES, "YARA file")?;
    import_source(&source)
}

pub fn import_source(source: &str) -> Result<Conversion> {
    let source = strip_comments(source);
    let mut converted = Vec::new();
    let mut skipped = Vec::new();
    for block in rule_blocks(&source)? {
        match import_rule(&block) {
            Ok(rule) => converted.push(rule),
            Err(reason) => skipped.push(SkippedRule {
                rule: block.name.clone(),
                reason: format!("{reason:#}"),
            }),
        }
    }
    let mut output = String::from(
        "# Generated by Banshee from YARA rules. Review before use; matches are\n\
         # triage signals, not verdicts.\nversion = 1\n",
    );
    for rule in &skipped {
        writeln!(output, "# skipped {}: {}", rule.rule, rule.reason).expect("string write");
    }
    for rule in &converted {
        output.push('\n');
        output.push_str(rule);
    }
    if !converted.is_empty() {
        compile_source(&output).context("converted rules failed Banshee validation")?;
    }
    Ok(Conversion {
        output,
        converted: converted.len(),
        skipped,
        warnings: Vec::new(),
    })
}

struct RuleBlock {
    name: String,
    tags: Vec<String>,
    body: String,
}

/// Removes `//` and `/* */` comments outside quoted strings and regexes.
fn strip_comments(source: &str) -> String {
    let characters = source.chars().collect::<Vec<_>>();
    let mut output = String::with_capacity(source.len());
    let mut index = 0;
    let mut quote: Option<char> = None;
    while index < characters.len() {
        let character = characters[index];
        let next = characters.get(index + 1).copied();
        if let Some(delimiter) = quote {
            output.push(character);
            if character == '\\' {
                if let Some(next) = next {
                    output.push(next);
                }
                index += 2;
                continue;
            }
            if character == delimiter {
                quote = None;
            }
            index += 1;
            continue;
        }
        match (character, next) {
            ('/', Some('/')) => {
                while index < characters.len() && characters[index] != '\n' {
                    index += 1;
                }
            }
            ('/', Some('*')) => {
                index += 2;
                while index + 1 < characters.len()
                    && !(characters[index] == '*' && characters[index + 1] == '/')
                {
                    index += 1;
                }
                index += 2;
            }
            ('"', _) => {
                quote = Some('"');
                output.push(character);
                index += 1;
            }
            ('/', _) if output.trim_end().ends_with('=') => {
                // A regex string starts after `=`; keep its slashes literal.
                quote = Some('/');
                output.push(character);
                index += 1;
            }
            _ => {
                output.push(character);
                index += 1;
            }
        }
    }
    output
}

fn rule_blocks(source: &str) -> Result<Vec<RuleBlock>> {
    let header = regex!(
        r"(?m)^\s*(?:(?:private|global)\s+)*rule\s+([A-Za-z_][A-Za-z0-9_]*)\s*(?::\s*([A-Za-z0-9_\s]+?))?\s*\{"
    );
    let mut blocks = Vec::new();
    for captures in header.captures_iter(source) {
        let whole = captures.get(0).expect("whole match");
        let body_start = whole.end();
        let mut depth = 1;
        let mut quote: Option<char> = None;
        let mut end = None;
        // Last significant character outside strings: a `/` right after `=`
        // opens a regex, whose braces must not count.
        let mut previous = '{';
        let mut characters = source[body_start..].char_indices();
        while let Some((offset, character)) = characters.next() {
            match quote {
                Some(_) if character == '\\' => {
                    characters.next();
                }
                Some(delimiter) if character == delimiter => quote = None,
                Some(_) => {}
                None => match character {
                    '"' => quote = Some('"'),
                    '/' if previous == '=' => quote = Some('/'),
                    '{' => depth += 1,
                    '}' => {
                        depth -= 1;
                        if depth == 0 {
                            end = Some(body_start + offset);
                            break;
                        }
                    }
                    _ => {}
                },
            }
            if quote.is_none() && !character.is_whitespace() {
                previous = character;
            }
        }
        let end = end.with_context(|| format!("rule '{}' is not closed", &captures[1]))?;
        blocks.push(RuleBlock {
            name: captures[1].to_owned(),
            tags: captures
                .get(2)
                .map(|tags| {
                    tags.as_str()
                        .split_whitespace()
                        .map(str::to_owned)
                        .collect()
                })
                .unwrap_or_default(),
            body: source[body_start..end].to_owned(),
        });
    }
    if blocks.is_empty() {
        bail!("no YARA rules were found");
    }
    Ok(blocks)
}

/// Splits a rule body into its sections, which YARA requires in the order
/// meta, strings, condition. Each keyword is searched for only after the
/// previous section, so text inside earlier sections cannot start a new one.
fn sections(body: &str) -> Result<BTreeMap<&'static str, String>> {
    let mut found = Vec::new();
    let mut cursor = 0;
    let markers = [
        ("meta", regex!(r"(?:^|\s)meta\s*:")),
        ("strings", regex!(r"(?:^|\s)strings\s*:")),
        ("condition", regex!(r"(?:^|\s)condition\s*:")),
    ];
    for (name, marker) in markers {
        if let Some(matched) = marker.find(&body[cursor..]) {
            found.push((name, cursor + matched.start(), cursor + matched.end()));
            cursor += matched.end();
        }
    }
    let mut map = BTreeMap::new();
    for (index, (name, _, start)) in found.iter().enumerate() {
        let end = found.get(index + 1).map_or(body.len(), |next| next.1);
        map.insert(*name, body[*start..end].trim().to_owned());
    }
    if !map.contains_key("condition") {
        bail!("rule has no condition section");
    }
    Ok(map)
}

fn import_rule(block: &RuleBlock) -> Result<String> {
    let sections = sections(&block.body)?;
    let strings = parse_strings(sections.get("strings").map_or("", String::as_str))?;
    let meta = parse_meta(sections.get("meta").map_or("", String::as_str));
    let plan = plan_condition(&sections["condition"], &strings)?;

    let mut toml = String::new();
    writeln!(toml, "[[rules]]").expect("string write");
    // Banshee exports keep the original ID, which may contain `-` or `.`.
    let id = meta_value(&meta, "banshee_id")
        .filter(|id| !id.trim().is_empty() && id.len() <= 128)
        .unwrap_or(&block.name);
    writeln!(toml, "id = {}", toml_string(id)).expect("string write");
    if let Some(description) = meta_value(&meta, "description") {
        writeln!(toml, "description = {}", toml_string(description)).expect("string write");
    }
    if let Some(severity) = meta_value(&meta, "severity")
        .map(|value| value.to_ascii_lowercase())
        .filter(|value| {
            matches!(
                value.as_str(),
                "info" | "low" | "medium" | "high" | "critical"
            )
        })
    {
        writeln!(toml, "severity = {}", toml_string(&severity)).expect("string write");
    }
    if let Some(category) = meta_value(&meta, "category").filter(|value| value.len() <= 128) {
        writeln!(toml, "category = {}", toml_string(category)).expect("string write");
    }
    if let Some(confidence) = meta_value(&meta, "confidence")
        .map(|value| value.to_ascii_lowercase())
        .filter(|value| matches!(value.as_str(), "low" | "medium" | "high"))
    {
        writeln!(toml, "confidence = {}", toml_string(&confidence)).expect("string write");
    }
    if let Some(attack) = meta_value(&meta, "attack") {
        let identifiers = attack
            .split(',')
            .map(str::trim)
            .filter(|value| super::is_attack_identifier(value))
            .map(toml_string)
            .collect::<Vec<_>>();
        if !identifiers.is_empty() {
            writeln!(toml, "attack = [{}]", identifiers.join(", ")).expect("string write");
        }
    }
    for (key, value) in [
        ("min_entropy", plan.min_entropy),
        ("max_entropy", plan.max_entropy),
    ] {
        if let Some(value) = value {
            writeln!(toml, "{key} = {value:?}").expect("string write");
        }
    }
    for (key, value) in [("min_size", plan.min_size), ("max_size", plan.max_size)] {
        if let Some(value) = value {
            writeln!(toml, "{key} = {value}").expect("string write");
        }
    }
    let primary = plan.primary;
    writeln!(toml, "kind = {}", toml_string(&primary.kind.to_string())).expect("string write");
    writeln!(toml, "pattern = {}", toml_string(&primary.pattern)).expect("string write");
    if primary.case_insensitive {
        writeln!(toml, "case_insensitive = true").expect("string write");
    }
    if primary.encoding != TextEncoding::Ascii {
        writeln!(toml, "encoding = \"{}\"", primary.encoding).expect("string write");
    }
    if plan.min_matches > 1 {
        writeln!(toml, "min_matches = {}", plan.min_matches).expect("string write");
    }
    let tags = block
        .tags
        .iter()
        .take(super::MAX_TAGS_PER_RULE)
        .map(|tag| toml_string(tag))
        .collect::<Vec<_>>();
    if !tags.is_empty() {
        writeln!(toml, "tags = [{}]", tags.join(", ")).expect("string write");
    }
    let references = meta
        .iter()
        .filter(|(key, _)| matches!(key.as_str(), "reference" | "references" | "url" | "link"))
        .map(|(_, value)| toml_string(value))
        .take(super::MAX_REFERENCES_PER_RULE)
        .collect::<Vec<_>>();
    if !references.is_empty() {
        writeln!(toml, "references = [{}]", references.join(", ")).expect("string write");
    }
    if !plan.file_types.is_empty() {
        let types = plan
            .file_types
            .iter()
            .map(|file_type| toml_string(&file_type.to_string()))
            .collect::<Vec<_>>();
        writeln!(toml, "file_types = [{}]", types.join(", ")).expect("string write");
    }
    for (group, conditions) in [("all", &plan.all), ("any", &plan.any)] {
        for condition in conditions {
            writeln!(toml, "\n[[rules.{group}]]").expect("string write");
            writeln!(toml, "kind = {}", toml_string(&condition.kind.to_string()))
                .expect("string write");
            writeln!(toml, "pattern = {}", toml_string(&condition.pattern)).expect("string write");
            if condition.case_insensitive {
                writeln!(toml, "case_insensitive = true").expect("string write");
            }
            if condition.encoding != TextEncoding::Ascii {
                writeln!(toml, "encoding = \"{}\"", condition.encoding).expect("string write");
            }
            if let Some(bytes) = condition.within {
                writeln!(toml, "within = {bytes}").expect("string write");
            }
        }
    }
    // Each rule must also compile on its own so a failure names the rule.
    compile_source(&format!("version = 1\n{toml}"))
        .context("converted rule failed Banshee validation")?;
    Ok(toml)
}

/// Meta values keyed by lowercase identifier; repeated keys keep each value.
fn parse_meta(section: &str) -> Vec<(String, String)> {
    let line = regex!(r#"(?m)^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*"((?:[^"\\]|\\.)*)""#);
    line.captures_iter(section)
        .map(|captures| {
            (
                captures[1].to_ascii_lowercase(),
                unescape_yara_text(&captures[2]).map_or_else(
                    || captures[2].to_owned(),
                    |bytes| String::from_utf8_lossy(&bytes).into_owned(),
                ),
            )
        })
        .collect()
}

fn meta_value<'a>(meta: &'a [(String, String)], key: &str) -> Option<&'a String> {
    meta.iter()
        .find(|(candidate, _)| candidate == key)
        .map(|(_, value)| value)
}

fn parse_strings(section: &str) -> Result<Vec<(String, YaraString)>> {
    let definition = regex!(
        r#"(?s)\$([A-Za-z0-9_]*)\s*=\s*("(?:[^"\\]|\\.)*"|\{[^}]*\}|/(?:[^/\\\n]|\\.)*/[is]*)([^$]*)"#
    );
    let mut strings = Vec::new();
    for captures in definition.captures_iter(section) {
        let name = captures[1].to_owned();
        let value = &captures[2];
        let modifiers = captures[3].split_whitespace().collect::<Vec<_>>();
        let mut case_insensitive = false;
        let (mut ascii, mut wide) = (false, false);
        for modifier in &modifiers {
            match *modifier {
                "nocase" => case_insensitive = true,
                "ascii" => ascii = true,
                "wide" => wide = true,
                "private" => {}
                other => bail!("string ${name} uses unsupported modifier '{other}'"),
            }
        }
        // YARA: ascii is the default; wide alone means UTF-16LE only.
        let encoding = match (ascii, wide) {
            (_, false) => TextEncoding::Ascii,
            (false, true) => TextEncoding::Wide,
            (true, true) => TextEncoding::Both,
        };
        if wide && value.starts_with('{') {
            bail!("string ${name} uses 'wide' on a hex string");
        }
        let string = if let Some(text) = value.strip_prefix('"') {
            let bytes = unescape_yara_text(&text[..text.len() - 1])
                .with_context(|| format!("string ${name} has an invalid escape"))?;
            match String::from_utf8(bytes) {
                Ok(text) => YaraString {
                    kind: RuleKind::Literal,
                    pattern: text,
                    case_insensitive,
                    encoding,
                    within: None,
                },
                Err(_) if wide => bail!("string ${name} is not UTF-8 text and uses 'wide'"),
                // Non-UTF-8 text strings become exact hex patterns.
                Err(error) => YaraString {
                    kind: RuleKind::Hex,
                    pattern: error
                        .into_bytes()
                        .iter()
                        .map(|byte| format!("{byte:02X}"))
                        .collect::<Vec<_>>()
                        .join(" "),
                    case_insensitive: false,
                    encoding: TextEncoding::Ascii,
                    within: None,
                },
            }
        } else if let Some(hex) = value.strip_prefix('{') {
            let hex = hex[..hex.len() - 1].trim();
            if hex.contains(['[', '(', '|', '~']) {
                bail!("hex string ${name} uses jumps, alternatives or negation");
            }
            parse_hex_pattern(hex)
                .with_context(|| format!("hex string ${name} is not supported"))?;
            YaraString {
                kind: RuleKind::Hex,
                pattern: hex.split_whitespace().collect::<Vec<_>>().join(" "),
                case_insensitive: false,
                encoding: TextEncoding::Ascii,
                within: None,
            }
        } else {
            let end = value.rfind('/').expect("regex has a closing slash");
            let flags = &value[end + 1..];
            let body = value[1..end].replace("\\/", "/");
            let dotall = if flags.contains('s') { "(?s)" } else { "" };
            YaraString {
                kind: RuleKind::Regex,
                pattern: format!("{dotall}{body}"),
                case_insensitive: case_insensitive || flags.contains('i'),
                encoding,
                within: None,
            }
        };
        strings.push((name, string));
    }
    Ok(strings)
}

fn unescape_yara_text(value: &str) -> Option<Vec<u8>> {
    let mut output = Vec::with_capacity(value.len());
    let mut characters = value.chars();
    while let Some(character) = characters.next() {
        if character != '\\' {
            let mut buffer = [0; 4];
            output.extend_from_slice(character.encode_utf8(&mut buffer).as_bytes());
            continue;
        }
        match characters.next()? {
            'n' => output.push(b'\n'),
            'r' => output.push(b'\r'),
            't' => output.push(b'\t'),
            '"' => output.push(b'"'),
            '\\' => output.push(b'\\'),
            'x' => {
                let hex = [characters.next()?, characters.next()?]
                    .iter()
                    .collect::<String>();
                output.push(u8::from_str_radix(&hex, 16).ok()?);
            }
            _ => return None,
        }
    }
    Some(output)
}

struct ConditionPlan {
    primary: YaraString,
    all: Vec<YaraString>,
    any: Vec<YaraString>,
    min_matches: usize,
    file_types: Vec<RuleFileType>,
    min_entropy: Option<f64>,
    max_entropy: Option<f64>,
    min_size: Option<u64>,
    max_size: Option<u64>,
}

fn plan_condition(condition: &str, strings: &[(String, YaraString)]) -> Result<ConditionPlan> {
    if strings.is_empty() {
        bail!("rules without strings have no Banshee pattern");
    }
    let lookup = |name: &str| {
        strings
            .iter()
            .find(|(candidate, _)| candidate == name)
            .map(|(_, string)| string.clone())
            .with_context(|| format!("condition references unknown string ${name}"))
    };
    let normalized = condition.split_whitespace().collect::<Vec<_>>().join(" ");
    let mut required = Vec::new();
    let mut any = Vec::new();
    let mut min_matches = 1;
    let mut file_types = Vec::new();
    let (mut min_entropy, mut max_entropy) = (None, None);
    let (mut min_size, mut max_size): (Option<u64>, Option<u64>) = (None, None);
    let mut has_proximity = false;
    let filesize = regex!(r"^filesize (<=|<|>=|>) (\d+)(KB|MB)?$");
    let proximity = regex!(r"^for any i in \(1 ?\.\. ?#([A-Za-z0-9_]+)\) ?: ?\((.*)\)$");
    let near = regex!(
        r"^\$([A-Za-z0-9_]+) in \(@([A-Za-z0-9_]+)\[i\] ?\.\. ?@([A-Za-z0-9_]+)\[i\] ?\+ ?(\d+)\)$"
    );
    let count = regex!(r"^#([A-Za-z0-9_]*) (>=|>) (\d+)$");
    let set = regex!(r"^(any|all) of \(([^)]*)\)$");
    let entropy = regex!(r"^math\.entropy\(0, ?filesize\) (>=|<=) ([0-9]+(?:\.[0-9]+)?)$");
    // `($a, $b*)` selects named strings and prefixes, as in YARA string sets.
    let select = |list: &str| -> Result<Vec<YaraString>> {
        let mut selected = Vec::new();
        for item in list.split(',').map(str::trim) {
            let name = item
                .strip_prefix('$')
                .with_context(|| format!("unsupported string set item '{item}'"))?;
            match name.strip_suffix('*') {
                Some(prefix) => selected.extend(
                    strings
                        .iter()
                        .filter(|(candidate, _)| candidate.starts_with(prefix))
                        .map(|(_, string)| string.clone()),
                ),
                None => selected.push(lookup(name)?),
            }
        }
        if selected.is_empty() {
            bail!("string set '({list})' matches no strings");
        }
        Ok(selected)
    };
    let identifier = regex!(r"^\$([A-Za-z0-9_]*)$");

    for term in split_top_level(&normalized, " and ") {
        let term = strip_parentheses(term);
        if term == "all of them" {
            required.extend(strings.iter().map(|(_, string)| string.clone()));
        } else if term == "any of them" || term == "1 of them" {
            any.extend(strings.iter().map(|(_, string)| string.clone()));
        } else if let Some(captures) = set.captures(term) {
            let selected = select(&captures[2])?;
            if &captures[1] == "all" {
                required.extend(selected);
            } else {
                any.extend(selected);
            }
        } else if let Some(captures) = entropy.captures(term) {
            let value = captures[2]
                .parse::<f64>()
                .context("invalid entropy bound")?;
            if &captures[1] == ">=" {
                min_entropy = Some(value);
            } else {
                max_entropy = Some(value);
            }
        } else if let Some(captures) = proximity.captures(term) {
            // `for any i in (1..#a) : ($b in (@a[i]..@a[i] + N) and ...)`:
            // $a becomes the primary pattern, the others `within` it.
            let anchor = &captures[1];
            let mut near_anchor = Vec::new();
            for part in split_top_level(captures[2].trim(), " and ") {
                let part = strip_parentheses(part.trim());
                let item = near.captures(part).with_context(|| {
                    format!("unsupported proximity term '{part}' (only $x in (@a[i]..@a[i] + N))")
                })?;
                if &item[2] != anchor || &item[3] != anchor {
                    bail!("proximity term '{part}' must refer to ${anchor}");
                }
                let mut string = lookup(&item[1])?;
                string.within = Some(
                    item[4]
                        .parse::<usize>()
                        .context("invalid proximity distance")?,
                );
                near_anchor.push(string);
            }
            if has_proximity || min_matches > 1 {
                bail!("only one proximity loop is supported, without a string count");
            }
            has_proximity = true;
            // The anchor must be the primary pattern, so it goes first.
            required.insert(0, lookup(anchor)?);
            required.extend(near_anchor);
        } else if let Some(captures) = filesize.captures(term) {
            let unit: u64 = match captures.get(3).map(|unit| unit.as_str()) {
                Some("KB") => 1024,
                Some("MB") => 1024 * 1024,
                _ => 1,
            };
            let value = captures[2]
                .parse::<u64>()
                .ok()
                .and_then(|value| value.checked_mul(unit))
                .context("invalid filesize bound")?;
            // Several bounds narrow each other, as YARA's `and` does.
            match &captures[1] {
                "<=" => max_size = Some(max_size.map_or(value, |bound| bound.min(value))),
                "<" => {
                    let bound = value.saturating_sub(1);
                    max_size = Some(max_size.map_or(bound, |current| current.min(bound)));
                }
                ">=" => min_size = Some(min_size.map_or(value, |bound| bound.max(value))),
                _ => {
                    let bound = value.saturating_add(1);
                    min_size = Some(min_size.map_or(bound, |current| current.max(bound)));
                }
            }
        } else if let Some(captures) = identifier.captures(term) {
            required.push(lookup(&captures[1])?);
        } else if let Some(captures) = count.captures(term) {
            let threshold = captures[3]
                .parse::<usize>()
                .context("invalid string count")?;
            let minimum = if &captures[2] == ">" {
                threshold + 1
            } else {
                threshold
            };
            if !required.is_empty() || min_matches > 1 {
                bail!("only one string count is supported, on the first required string");
            }
            required.push(lookup(&captures[1])?);
            min_matches = minimum.max(1);
        } else if let Some(file_type) = magic_file_type(term) {
            file_types.push(file_type);
        } else if split_top_level(term, " or ").len() > 1 {
            for alternative in split_top_level(term, " or ") {
                let alternative = strip_parentheses(alternative);
                let captures = identifier.captures(alternative).with_context(|| {
                    format!("unsupported alternative '{alternative}' (only $strings)")
                })?;
                any.push(lookup(&captures[1])?);
            }
        } else {
            bail!("unsupported condition term '{term}'");
        }
    }

    let primary = if required.is_empty() {
        // "any of them" with nothing else required: one alternation pattern.
        let alternatives = std::mem::take(&mut any);
        if alternatives.is_empty() {
            bail!("condition does not require any string");
        }
        alternation(&alternatives)?
    } else {
        required.remove(0)
    };
    Ok(ConditionPlan {
        primary,
        all: required,
        any,
        min_matches,
        file_types,
        min_entropy,
        max_entropy,
        min_size,
        max_size,
    })
}

/// Combines strings into one bytes regex that matches if any of them does.
fn alternation(strings: &[YaraString]) -> Result<YaraString> {
    if let [only] = strings {
        return Ok(only.clone());
    }
    let parts = strings
        .iter()
        .map(|string| {
            Ok(match string.kind {
                RuleKind::Literal if string.case_insensitive => {
                    format!("(?i:{})", literal_pattern(&string.pattern, string.encoding))
                }
                RuleKind::Literal => {
                    format!("(?:{})", literal_pattern(&string.pattern, string.encoding))
                }
                RuleKind::Regex if string.case_insensitive => {
                    format!("(?i:{})", regex_pattern(&string.pattern, string.encoding)?)
                }
                RuleKind::Regex => {
                    format!("(?:{})", regex_pattern(&string.pattern, string.encoding)?)
                }
                RuleKind::Hex => {
                    let bytes = parse_hex_pattern(&string.pattern)?
                        .iter()
                        .map(|byte| {
                            byte.map_or_else(|| ".".to_owned(), |byte| format!("\\x{byte:02X}"))
                        })
                        .collect::<String>();
                    format!("(?s-u:{bytes})")
                }
            })
        })
        .collect::<Result<Vec<_>>>()?;
    Ok(YaraString {
        kind: RuleKind::Regex,
        pattern: parts.join("|"),
        case_insensitive: false,
        encoding: TextEncoding::Ascii,
        within: None,
    })
}

fn magic_file_type(term: &str) -> Option<RuleFileType> {
    let compact = term.replace(' ', "").to_ascii_lowercase();
    Some(match compact.as_str() {
        "uint16(0)==0x5a4d" => RuleFileType::Pe,
        "uint32(0)==0x464c457f" => RuleFileType::Elf,
        "uint32(0)==0x04034b50" => RuleFileType::Zip,
        "uint16(0)==0x8b1f" => RuleFileType::Gzip,
        _ => return None,
    })
}

fn split_top_level<'a>(text: &'a str, separator: &str) -> Vec<&'a str> {
    let mut parts = Vec::new();
    let mut depth = 0_i32;
    let mut start = 0;
    let bytes = text.as_bytes();
    let mut index = 0;
    while index < bytes.len() {
        match bytes[index] {
            b'(' => depth += 1,
            b')' => depth -= 1,
            // Compare bytes: `index` may sit inside a multi-byte character, and
            // an ASCII separator match always starts on a character boundary.
            _ if depth == 0 && bytes[index..].starts_with(separator.as_bytes()) => {
                parts.push(text[start..index].trim());
                index += separator.len();
                start = index;
                continue;
            }
            _ => {}
        }
        index += 1;
    }
    parts.push(text[start..].trim());
    parts
}

fn strip_parentheses(term: &str) -> &str {
    let mut term = term.trim();
    while term.starts_with('(') && term.ends_with(')') {
        let inner = &term[1..term.len() - 1];
        // Only strip a pair that encloses the whole term.
        let mut depth = 0_i32;
        let balanced = inner.chars().all(|character| {
            match character {
                '(' => depth += 1,
                ')' => depth -= 1,
                _ => {}
            }
            depth >= 0
        });
        if !balanced || depth != 0 {
            break;
        }
        term = inner.trim();
    }
    term
}

pub(super) fn toml_string(value: &str) -> String {
    let mut output = String::from("\"");
    for character in value.chars() {
        match character {
            '"' => output.push_str("\\\""),
            '\\' => output.push_str("\\\\"),
            '\n' => output.push_str("\\n"),
            '\r' => output.push_str("\\r"),
            '\t' => output.push_str("\\t"),
            character if character.is_control() => {
                write!(output, "\\u{:04X}", u32::from(character)).expect("string write");
            }
            character => output.push(character),
        }
    }
    output.push('"');
    output
}

